"""Derive the EAGLMacroContext dispatch slot of every gl* export of the real OpenGLES.framework (22H352) and write
src/macro_slots.c: { "glName", offset }. Only name -> number facts are emitted; no code or data of Apple's binary.

Each exported gl* function is a thin stub: `mrs x8, tpidrro_el0; ldr ctx,[x8,#0xf0]` (the current GLI context), then
`ldr fn,[ctx,#SLOT]` with the renderer in `[ctx,#0x20]`, shifts its arguments up by one and jumps. QuartzCore holds the
EAGLMacroContext pointer = ctx+0x20 (rend at +0, slots from +8), so macro offset = SLOT - 0x20.

Setup as for dsc_oglinfo.py (DSC_DIR=...; venv with capstone). Usage: dsc_slotmap.py > ../src/macro_slots.c
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', '..', 'tools', 'renegade', 'dsctools'))
assert os.environ.get('DSC_DIR'), 'set DSC_DIR'
from symb import rd, IMGS, exports
from capstone import Cs, CS_ARCH_ARM64, CS_MODE_ARM

md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
ia = [a for a, p in IMGS if 'OpenGLES.framework/OpenGLES' in p][0]
res = {}
for a, n in sorted(exports(ia).items(), key=lambda x: x[1]):
    if not n.startswith('_gl'):
        continue
    ins = list(md.disasm(rd(a, 0xa0), a))
    if len(ins) < 4 or ins[0].mnemonic != 'mrs' or 'tpidrro_el0' not in ins[0].op_str:
        sys.stderr.write('no slot: %s\n' % n); continue
    ctx = None
    for i in ins[1:3]:
        if i.mnemonic == 'ldr' and '#0xf0]' in i.op_str:
            ctx = i.op_str.split(',')[0]
    for i in ins[3:40]:
        if ctx and i.mnemonic == 'ldr' and ('[%s, #' % ctx) in i.op_str:
            off = int(i.op_str.split('#')[1].rstrip(']!'), 16)
            if off != 0x20 and off >= 0x28:
                res[n[1:]] = off - 0x20
                break
    else:
        sys.stderr.write('no slot: %s\n' % n)
print('// SPDX-License-Identifier: MIT')
print('// GENERATED by tools/dsc_slotmap.py: byte offset of each entry point in the EAGLMacroContext (22H352).')
print('#include "macro_ctx.h"')
print('const struct macro_slot macro_slots[] = {')
for n, o in sorted(res.items()):
    print('    { "%s", 0x%x },' % (n, o))
print('    { 0, 0 } };')
print('const int macro_nslots = %d;' % len(res))
