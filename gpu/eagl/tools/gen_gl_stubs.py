#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Generate src/gl_stubs.c: one exported trampoline per C entry point of OpenGLES.framework.

The list of names comes from the PUBLIC iPhoneOS SDK stub library (OpenGLES.tbd), so it is exactly the set
of `_gl*` symbols the system OpenGLES.framework exports (checked against the 22H352 dyld cache, see
docs/GPU_EAGL.md). Each trampoline jumps through gl_tab[i]; gl_tab is filled at load time from Mesa's
OSMesaGetProcAddress (see src/gl_resolve.c), with suffix-stripping aliases and a few no-op debug entry points.

  gen_gl_stubs.py [TBD] > src/gl_stubs.c        (TBD defaults to the iphoneos SDK's OpenGLES.tbd)
"""
import re, subprocess, sys

def sdk_tbd():
    sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
    return sdk + '/System/Library/Frameworks/OpenGLES.framework/OpenGLES.tbd'

def main():
    path = sys.argv[1] if len(sys.argv) > 1 else sdk_tbd()
    txt = open(path).read()
    syms = sorted(set(re.findall(r'\b_(gl[A-Za-z0-9_]+)\b', txt)))
    out = []
    w = out.append
    w('// SPDX-License-Identifier: MIT')
    w('// GENERATED by tools/gen_gl_stubs.py from the iphoneos SDK OpenGLES.tbd: do not edit.')
    w('#include "gl_tab.h"')
    w('')
    w('#define GL_NFUNCS %d' % len(syms))
    w('void *gl_tab[GL_NFUNCS + 1];')
    w('const char *const gl_names[GL_NFUNCS + 1] = {')
    for s in syms:
        w('    "%s",' % s)
    w('    0 };')
    w('const int gl_nfuncs = GL_NFUNCS;')
    w('')
    w('#if defined(__arm64__) || defined(__aarch64__)')
    w('#if __has_feature(ptrauth_calls)')
    w('#define GL_BR "braaz x16"')
    w('#else')
    w('#define GL_BR "br x16"')
    w('#endif')
    w('#define GL_STUB(name, idx) \\')
    w('    __attribute__((visibility("default"), naked, used)) void name(void) { __asm__ volatile( \\')
    w('        "mov x17, #" #idx "\\n" \\')
    w('        "adrp x16, _gl_tab@PAGE\\n" \\')
    w('        "add x16, x16, _gl_tab@PAGEOFF\\n" \\')
    w('        "ldr x16, [x16, #" #idx "*8]\\n" \\')
    w('        GL_BR); }')
    w('#else')
    w('#error arm64 only')
    w('#endif')
    w('')
    for i, s in enumerate(syms):
        w('GL_STUB(%s, %d)' % (s, i))
    # Macro-context thunks: CoreAnimation calls fn(rend, args...) through EAGLMacroContext; drop `rend` (x0) by
    # shifting x1..x7 down and tail-call the same entry point. Entry points with 8+ arguments need a C wrapper
    # (src/macro_ctx.c, mw_<base name>) because their arguments spill to the stack.
    w('')
    w('#define GL_MSTUB(name, idx) \\')
    w('    __attribute__((visibility("hidden"), naked, used)) void ms_##name(void) { __asm__ volatile( \\')
    w('        "adrp x16, _gl_tab@PAGE\\n" \\')
    w('        "add x16, x16, _gl_tab@PAGEOFF\\n" \\')
    w('        "ldr x16, [x16, #" #idx "*8]\\n" \\')
    w('        "mov x0, x1\\n mov x1, x2\\n mov x2, x3\\n mov x3, x4\\n mov x4, x5\\n mov x5, x6\\n mov x6, x7\\n" \\')
    w('        GL_BR); }')
    w('')
    wide = ['CompressedTexImage2D', 'CopyTexImage2D', 'CopyTexSubImage2D', 'CompressedTexSubImage2D', 'TexImage2D', 'TexSubImage2D', 'TexImage3D',
            'TexSubImage3D', 'CopyTexSubImage3D', 'CompressedTexImage3D', 'CompressedTexSubImage3D', 'BlitFramebuffer']
    def base(n):
        for suf in ('OES', 'EXT', 'APPLE', 'ANGLE', 'KHR', 'IMG'):
            if n.endswith(suf): return n[2:-len(suf)]
        return n[2:]
    # Tracing variant (EAGL_TRACE=1): save the argument registers, log the call (name + first four integer args after `rend`), forward.
    w('#define GL_TSTUB(name, idx) \\')
    w('    __attribute__((visibility("hidden"), naked, used)) void mt_##name(void) { __asm__ volatile( \\')
    w('        "stp x29, x30, [sp, #-16]!\\n mov x29, sp\\n sub sp, sp, #144\\n" \\')
    w('        "stp x0, x1, [sp, #0]\\n stp x2, x3, [sp, #16]\\n stp x4, x5, [sp, #32]\\n stp x6, x7, [sp, #48]\\n" \\')
    w('        "stp q0, q1, [sp, #64]\\n stp q2, q3, [sp, #96]\\n" \\')
    w('        "mov x0, #" #idx "\\n ldp x1, x2, [sp, #8]\\n ldp x3, x4, [sp, #24]\\n bl _gl_trace_hook\\n" \\')
    w('        "ldp x0, x1, [sp, #0]\\n ldp x2, x3, [sp, #16]\\n ldp x4, x5, [sp, #32]\\n ldp x6, x7, [sp, #48]\\n" \\')
    w('        "ldp q0, q1, [sp, #64]\\n ldp q2, q3, [sp, #96]\\n add sp, sp, #144\\n ldp x29, x30, [sp], #16\\n" \\')
    w('        "adrp x16, _gl_tab@PAGE\\n add x16, x16, _gl_tab@PAGEOFF\\n ldr x16, [x16, #" #idx "*8]\\n" \\')
    w('        "mov x0, x1\\n mov x1, x2\\n mov x2, x3\\n mov x3, x4\\n mov x4, x5\\n mov x5, x6\\n mov x6, x7\\n" \\')
    w('        GL_BR); }')
    w('extern void gl_trace_hook(int idx, long a, long b, long c, long d);')
    w('')
    for i, s in enumerate(syms):
        if base(s) not in wide:
            w('GL_MSTUB(%s, %d)' % (s, i))
            w('GL_TSTUB(%s, %d)' % (s, i))
    for b in wide:
        w('extern void mw_%s(void);' % b)
    w('')
    w('void *const ms_thunks[GL_NFUNCS + 1] = {')
    for i, s in enumerate(syms):
        w('    (void *)%s,' % (('mw_' + base(s)) if base(s) in wide else ('ms_' + s)))
    w('    0 };')
    w('void *const mt_thunks[GL_NFUNCS + 1] = {')
    for i, s in enumerate(syms):
        w('    (void *)%s,' % (('mw_' + base(s)) if base(s) in wide else ('mt_' + s)))
    w('    0 };')
    sys.stdout.write('\n'.join(out) + '\n')

main()
